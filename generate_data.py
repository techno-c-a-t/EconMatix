def build_and_save():
    # Собираем матрицу: строки = школы, столбцы = факторы
    school_ids = [s["id"] for s in SCHOOLS]
    matrix_rows = []
    for sid in school_ids:
        row = SCORES[sid]
        assert len(row) == 50, f"Для школы {sid} длина строки {len(row)} != 50"
        matrix_rows.append(row)

    matrix = np.array(matrix_rows, dtype=float)
    print(f"Исходная матрица: {matrix.shape[0]} школ (строки) × {matrix.shape[1]} факторов (столбцы)")

    transposed = matrix.T
    print(f"Транспонированная матрица: {transposed.shape[0]} факторов (строки) × {transposed.shape[1]} школ (столбцы)")

    # Сохраняем .npy файлы
    np.save("schools_matrix.npy", matrix)
    np.save("schools_matrix_transposed.npy", transposed)
    print("Сохранены schools_matrix.npy и schools_matrix_transposed.npy")

    # Формируем полный структурированный JSON с описаниями и пояснениями
    full_data = {
        "metadata": {
            "title": "Матрица экономических школ и критериев анализа",
            "schools_count": len(SCHOOLS),
            "factors_count": len(FACTORS),
            "score_range": [-1.0, 1.0],
            "score_meaning": {
                "-1.0": "Категорическое отрицание / крайний анти-приоритет",
                "-0.5": "Существенное несогласие / вторичность фактора",
                "0.0": "Нейтрально / нерелевантно / отсутствие акцента",
                "+0.5": "Умеренная поддержка / признание значимости",
                "+1.0": "Фундаментальный догмат / высший приоритет учения"
            }
        },
        "schools": SCHOOLS,
        "factors": FACTORS,
        "matrix": matrix.tolist(),
        "transposed_matrix": transposed.tolist()
    }

    with open("schools_data.json", "w", encoding="utf-8") as f:
        json.dump(full_data, f, ensure_ascii=False, indent=2)
    print("Сохранен schools_data.json")

if __name__ == "__main__":
    build_and_save()
